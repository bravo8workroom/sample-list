-- ============================================================
--  사진 용량 한도 맞추기 (photo-size-limit-migration.sql)
--  Supabase 대시보드 → SQL Editor 에 "이 파일만" 붙여넣고 [Run] 한 번.
--
--  왜 필요한가:
--   · 앱은 "한 번에 합계 50MB"까지만 담기게 막고, 넘으면 손님에게 안내한다.
--   · 그런데 버킷에 용량 제한이 설정돼 있지 않아 프로젝트 기본값(보통 50MB)이
--     적용되는데, 앱 한도와 숫자가 같아서 경계에서 맞붙는다.
--     → 딱 50MB짜리 사진 1장은 앱은 통과시키는데 서버가 거부할 수 있고,
--       그러면 손님은 이유 없이 "일부 저장 실패"만 보게 된다.
--   · 버킷 한도를 52MB로 한 칸 올려두면 항상 앱의 안내가 먼저 걸린다.
--     (손님이 실제로 올릴 수 있는 양은 그대로 50MB — 이 파일은 여유만 준다)
-- ============================================================

update storage.buckets
   set file_size_limit = 54525952           -- 52MB (앱 한도 50MB + 여유 2MB)
 where id = 'sample-photos';

-- 확인용 — file_size_limit 이 54525952 로 나오면 적용된 것
select id, public, file_size_limit
  from storage.buckets
 where id = 'sample-photos';
